#!/usr/bin/env python3
"""Pack the complete Supra2-IMG runtime image and emit its RTL address map."""

from __future__ import annotations

import argparse
import hashlib
import json
from dataclasses import dataclass
from pathlib import Path

import numpy as np
from compiler.supra2.prepare_timestep_adaln import prepare as prepare_timestep_adaln


ROOT = Path(__file__).resolve().parents[2]
DEFAULT_EXPORT = ROOT / "build" / "supra2_hw_export" / "export"
DEFAULT_WEIGHT_IMAGE = ROOT / "build" / "supra2_quant_export"
DEFAULT_OUTPUT = ROOT / "build" / "supra2_dit_ddr_image"
AXI_BYTES = 64
WEIGHT_TILE_BYTES = 1024
BLOCK_STAGE_SUFFIXES = (
    "self_attn.qkv",
    "self_attn.proj",
    "cross_attn.q",
    "cross_attn.kv",
    "cross_attn.proj",
    "mlp.0",
    "mlp.2",
)


@dataclass(frozen=True)
class Component:
    name: str
    alignment: int
    source: Path | None = None
    source_offset: int = 0
    size: int = 0
    data: bytes | None = None
    metadata: dict | None = None


def _sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _array_bytes(npz_path: Path, key: str, dtype: str) -> tuple[bytes, list[int]]:
    with np.load(npz_path, allow_pickle=False) as archive:
        if key not in archive:
            raise KeyError(f"{key!r} is missing from {npz_path}")
        array = np.asarray(archive[key], dtype=dtype, order="C")
    return array.tobytes(order="C"), list(array.shape)


def _align(value: int, alignment: int) -> int:
    return (value + alignment - 1) // alignment * alignment


def _source_component(name: str, path: Path, offset: int, size: int,
                      alignment: int, metadata: dict | None = None) -> Component:
    if not path.is_file():
        raise FileNotFoundError(path)
    if offset < 0 or size <= 0 or offset + size > path.stat().st_size:
        raise ValueError(f"invalid source range for {name}: {offset}+{size} in {path}")
    return Component(name, alignment, path, offset, size, None, metadata)


def _memory_component(name: str, data: bytes, metadata: dict | None = None) -> Component:
    return Component(name, AXI_BYTES, None, 0, len(data), data, metadata)


def _sv_array(name: str, values: list[int], width: int = 8) -> list[str]:
    lines = [f"    localparam integer {name} [0:{len(values)-1}] = '{{"]
    for start in range(0, len(values), width):
        end = min(start + width, len(values))
        suffix = "," if end < len(values) else ""
        lines.append("        " + ", ".join(str(v) for v in values[start:end]) + suffix)
    lines.append("    };")
    return lines


def _sv_matrix(name: str, values: list[list[int]]) -> list[str]:
    lines = [f"    localparam integer {name} [0:{len(values)-1}][0:{len(values[0])-1}] = '{{"]
    for row_index, row in enumerate(values):
        suffix = "," if row_index < len(values) - 1 else ""
        lines.append("        '{" + ", ".join(str(int(value)) for value in row) + "}" + suffix)
    lines.append("    };")
    return lines


def _write_layout_sv(path: Path, manifest: dict) -> None:
    qlayers = manifest["quantized_layers"]
    passthrough = manifest["passthrough_tensors"]
    runtime = manifest["runtime_inputs"]
    passthrough_ids = manifest["passthrough_ids"]
    lines = [
        "// Generated by prepare_dit_ddr_image.py; do not edit.",
        "package supra2_dit_ddr_layout;",
        f"    localparam integer DDR_BASE = 32'h{manifest['ddr_base']:08x};",
        f"    localparam integer PAYLOAD_BYTES = {manifest['payload_bytes']};",
        f"    localparam integer QLAYER_COUNT = {len(qlayers)};",
        f"    localparam integer PASSTHROUGH_COUNT = {len(passthrough)};",
        f"    localparam integer BLOCK_COUNT = {len(manifest['block_stage_layer_ids'])};",
        f"    localparam integer BLOCK_STAGE_COUNT = {len(BLOCK_STAGE_SUFFIXES)};",
        "    localparam integer WEIGHT_TILE_BYTES = 1024;",
        "    localparam integer TOKEN_COUNT = 256;",
        "    localparam integer CFG_ROWS = 512;",
        "    localparam integer MODEL_WIDTH = 576;",
        "    localparam integer ATTENTION_HEADS = 9;",
        "    localparam integer HEAD_WIDTH = 64;",
        "    localparam integer CONTEXT_TOKENS = 128;",
        "    localparam integer FLOW_STEPS = 50;",
        f"    localparam integer X_EMBED_LAYER_ID = {manifest['x_embed_layer_id']};",
        f"    localparam integer CTX_PROJ_LAYER_ID = {manifest['ctx_proj_layer_id']};",
    ]
    for name, sv_name in (
        ("pos_embed", "POS_EMBED"),
        ("t_embed.mlp.0.weight", "T_EMBED_MLP0_WEIGHT"),
        ("t_embed.mlp.0.bias", "T_EMBED_MLP0_BIAS"),
        ("t_embed.mlp.2.weight", "T_EMBED_MLP2_WEIGHT"),
        ("t_embed.mlp.2.bias", "T_EMBED_MLP2_BIAS"),
        ("final.linear.weight", "FINAL_LINEAR_WEIGHT"),
        ("final.linear.bias", "FINAL_LINEAR_BIAS"),
        ("final.adaln.1.weight", "FINAL_ADALN_WEIGHT"),
        ("final.adaln.1.bias", "FINAL_ADALN_BIAS"),
    ):
        lines.append(f"    localparam integer {sv_name}_ID = {passthrough_ids[name]};")
    runtime_sv_names = {
        "z0_fp16": "Z0",
        "ctx_all_fp16": "CTX_ALL",
        "mask_all_fp16": "MASK_ALL",
        "t_schedule_fp32": "T_SCHEDULE",
        "skip_trace_u8": "SKIP_TRACE",
        "block_adaln_params_fp16": "BLOCK_ADALN_RUNTIME",
        "final_adaln_params_fp16": "FINAL_ADALN_RUNTIME",
        "timestep_embedding_fp16": "T_EMBED_RUNTIME",
    }
    for item in runtime:
        sv_prefix = runtime_sv_names[item["name"]]
        lines.append(f"    localparam integer {sv_prefix}_OFFSET = {item['offset']};")
        lines.append(f"    localparam integer {sv_prefix}_BYTES = {item['bytes']};")
    for field, sv_name in (
        ("weight_offset", "QLAYER_WEIGHT_OFFSET"),
        ("scale_offset", "QLAYER_SCALE_OFFSET"),
        ("bias_offset", "QLAYER_BIAS_OFFSET"),
        ("weight_bytes", "QLAYER_WEIGHT_BYTES"),
        ("scale_bytes", "QLAYER_SCALE_BYTES"),
        ("bias_bytes", "QLAYER_BIAS_BYTES"),
        ("weight_beats", "QLAYER_WEIGHT_BEATS"),
        ("scale_beats", "QLAYER_SCALE_BEATS"),
        ("bias_beats", "QLAYER_BIAS_BEATS"),
        ("out", "QLAYER_OUT"),
        ("d_in", "QLAYER_IN"),
        ("h_block", "QLAYER_H_BLOCK"),
        ("n_tiles", "QLAYER_N_TILES"),
        ("k_tiles", "QLAYER_K_TILES"),
    ):
        lines.extend(_sv_array(sv_name, [int(q[field]) for q in qlayers]))
    lines.extend(_sv_array("QLAYER_N_TILE_STRIDE_BYTES", [
        int(q["k_tiles"]) * WEIGHT_TILE_BYTES for q in qlayers]))
    lines.extend(_sv_array("QLAYER_K_TILE_STRIDE_BYTES", [
        WEIGHT_TILE_BYTES for _ in qlayers]))
    for field, sv_name in (("offset", "PASSTHROUGH_OFFSET"),
                           ("bytes", "PASSTHROUGH_BYTES")):
        lines.extend(_sv_array(sv_name, [int(p[field]) for p in passthrough]))
    for field, sv_name in (("offset", "RUNTIME_INPUT_OFFSET"),
                           ("bytes", "RUNTIME_INPUT_BYTES")):
        lines.extend(_sv_array(sv_name, [int(v[field]) for v in runtime]))
    lines.append("    localparam integer BLOCK_STAGE_LAYER_ID [0:13][0:6] = '{")
    for block, ids in enumerate(manifest["block_stage_layer_ids"]):
        suffix = "," if block < len(manifest["block_stage_layer_ids"]) - 1 else ""
        lines.append("        '{" + ", ".join(str(int(v)) for v in ids) + "}" + suffix)
    lines.extend(["    };"])
    for field, sv_name in (
        ("weight_offset", "BLOCK_STAGE_WEIGHT_OFFSET"),
        ("scale_offset", "BLOCK_STAGE_SCALE_OFFSET"),
        ("bias_offset", "BLOCK_STAGE_BIAS_OFFSET"),
        ("weight_bytes", "BLOCK_STAGE_WEIGHT_BYTES"),
        ("scale_bytes", "BLOCK_STAGE_SCALE_BYTES"),
        ("bias_bytes", "BLOCK_STAGE_BIAS_BYTES"),
        ("weight_beats", "BLOCK_STAGE_WEIGHT_BEATS"),
        ("scale_beats", "BLOCK_STAGE_SCALE_BEATS"),
        ("bias_beats", "BLOCK_STAGE_BIAS_BEATS"),
        ("n_tile_stride_bytes", "BLOCK_STAGE_N_TILE_STRIDE_BYTES"),
        ("k_tile_stride_bytes", "BLOCK_STAGE_K_TILE_STRIDE_BYTES"),
        ("out", "BLOCK_STAGE_OUT"),
        ("d_in", "BLOCK_STAGE_IN"),
        ("n_tiles", "BLOCK_STAGE_N_TILES"),
        ("k_tiles", "BLOCK_STAGE_K_TILES"),
    ):
        lines.extend(_sv_matrix(sv_name, [
            [int(descriptor[field]) for descriptor in row]
            for row in manifest["block_stage_descriptors"]
        ]))
    for field, sv_name in (("weight_offset", "BLOCK_ADALN_WEIGHT_OFFSET"),
                           ("bias_offset", "BLOCK_ADALN_BIAS_OFFSET")):
        lines.extend(_sv_array(sv_name, [
            int(item[field]) for item in manifest["block_adaln_descriptors"]
        ]))
    lines.append("    localparam logic [13:0] BLOCK_SKIP_MASK [0:49] = '{")
    for step, mask in enumerate(manifest["block_skip_masks"]):
        suffix = "," if step < len(manifest["block_skip_masks"]) - 1 else ""
        lines.append(f"        14'h{int(mask):04x}{suffix}")
    lines.extend(["    };", "endpackage", ""])
    path.write_text("\n".join(lines), encoding="ascii")


def _build_components(export_dir: Path, weight_dir: Path) -> tuple[list[Component], list[dict], list[dict], list[dict], list[list[int]], list[int]]:
    image_path = weight_dir / "weight_image_manifest.json"
    if not image_path.is_file():
        raise FileNotFoundError(image_path)
    image = json.loads(image_path.read_text(encoding="utf-8"))
    qlayers = image["quantized_layers"]
    passthrough = image["passthrough_tensors"]
    if len(qlayers) != 100 or len(passthrough) != 37:
        raise ValueError(f"expected 100 quantized layers and 37 passthrough tensors, "
                         f"got {len(qlayers)} and {len(passthrough)}")

    golden_path = export_dir / "golden_steps.npz"
    runtime_values = []
    for key, dtype, name in (
        ("z0", "<f2", "z0_fp16"),
        ("ctx_all", "<f2", "ctx_all_fp16"),
        ("mask_all", "<f2", "mask_all_fp16"),
        ("t_schedule", "<f4", "t_schedule_fp32"),
    ):
        data, shape = _array_bytes(golden_path, key, dtype)
        runtime_values.append((name, data, {"source_key": key, "shape": shape, "dtype": dtype}))

    skip_path = export_dir / "skip_trace.json"
    skip = np.asarray(json.loads(skip_path.read_text(encoding="utf-8")), dtype=np.uint8)
    if skip.shape != (50, 14) or np.any(skip > 1):
        raise ValueError(f"expected a binary 50x14 skip trace, got {skip.shape}")
    skip_masks = [sum(int(skip[step, block]) << block for block in range(14))
                  for step in range(50)]
    runtime_values.append(("skip_trace_u8", skip.tobytes(order="C"),
                           {"shape": list(skip.shape), "dtype": "uint8"}))

    adaln_dir = DEFAULT_OUTPUT / "timestep_adaln"
    adaln_manifest = prepare_timestep_adaln(export_dir, adaln_dir)
    for name, field, shape in (
        ("block_adaln_params_fp16", "block_file", [50, 14, 8, 576]),
        ("final_adaln_params_fp16", "final_file", [50, 2, 576]),
        ("timestep_embedding_fp16", "timestep_embedding_file", [50, 576]),
    ):
        data = Path(adaln_manifest[field]).read_bytes()
        runtime_values.append((name, data, {"shape": shape, "dtype": "float16",
                                            "source": "compiled timestep/AdaLN table"}))

    components = [
        _memory_component(name, data, metadata)
        for name, data, metadata in runtime_values
    ]

    weight_file = weight_dir / "weights_int8_tiled.bin"
    scale_file = weight_dir / "weight_scales_fp32.bin"
    bias_file = weight_dir / "weight_biases_fp32.bin"
    for layer_id, layer in enumerate(qlayers):
        name = layer["name"]
        metadata = {"layer_id": layer_id,
                    "layer": name, "out": int(layer["out"]),
                    "d_in": int(layer["d_in"]), "h_block": int(layer["h_block"]),
                    "n_tiles": int(layer["n_tiles"]), "k_tiles": int(layer["k_tiles"])}
        components.append(_source_component(f"qweight:{name}", weight_file,
                                            int(layer["weight_offset"]),
                                            int(layer["weight_bytes"]),
                                            WEIGHT_TILE_BYTES, metadata))
        components.append(_source_component(f"qscale:{name}", scale_file,
                                            int(layer["scale_offset"]),
                                            int(layer["padded_vector_bytes"]),
                                            AXI_BYTES, metadata))
        components.append(_source_component(f"qbias:{name}", bias_file,
                                            int(layer["bias_offset"]),
                                            int(layer["padded_vector_bytes"]),
                                            AXI_BYTES, metadata))

    pass_file = weight_dir / "passthrough_fp16.bin"
    for tensor in passthrough:
        components.append(_source_component(
            f"passthrough:{tensor['name']}", pass_file, int(tensor["offset"]),
            int(tensor["bytes"]), AXI_BYTES,
            {"tensor_name": tensor["name"], "shape": tensor["shape"], "dtype": "float16"}))

    layer_ids = {record["name"]: i for i, record in enumerate(qlayers)}
    expected_blocks = []
    for block in range(14):
        row = []
        for suffix in BLOCK_STAGE_SUFFIXES:
            layer_name = f"blocks.{block}.{suffix}"
            if layer_name not in layer_ids:
                raise ValueError(f"missing required block layer {layer_name}")
            row.append(layer_ids[layer_name])
        expected_blocks.append(row)
    if "x_embed" not in layer_ids or "ctx_proj" not in layer_ids:
        raise ValueError("full image must include x_embed and ctx_proj")

    return components, qlayers, passthrough, runtime_values, expected_blocks, skip_masks


def build(export_dir: Path, weight_dir: Path, output_dir: Path,
          ddr_base: int = 0x0010_0000) -> dict:
    if ddr_base < 0 or ddr_base % AXI_BYTES:
        raise ValueError("DDR payload base must be nonnegative and 64-byte aligned")
    components, qlayers, passthrough, runtime_values, stage_ids, skip_masks = \
        _build_components(export_dir, weight_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    payload_path = output_dir / "supra2_dit_payload.bin"
    records = []
    offset = 0
    with payload_path.open("wb") as stream:
        for component in components:
            aligned = _align(offset, component.alignment)
            if aligned != offset:
                stream.write(bytes(aligned - offset))
            digest = hashlib.sha256()
            if component.data is not None:
                stream.write(component.data)
                digest.update(component.data)
            else:
                assert component.source is not None
                with component.source.open("rb") as source:
                    source.seek(component.source_offset)
                    remaining = component.size
                    while remaining:
                        chunk = source.read(min(1 << 20, remaining))
                        if not chunk:
                            raise ValueError(f"short read for {component.name}")
                        stream.write(chunk)
                        digest.update(chunk)
                        remaining -= len(chunk)
            record = {
                "name": component.name,
                "offset": aligned,
                "bytes": component.size,
                "alignment": component.alignment,
                "sha256": digest.hexdigest(),
            }
            if component.metadata:
                record.update(component.metadata)
            records.append(record)
            offset = aligned + component.size

        final_size = _align(offset, AXI_BYTES)
        if final_size > offset:
            stream.write(bytes(final_size - offset))
    if ddr_base + final_size > (1 << 32):
        raise ValueError("DDR payload exceeds the 32-bit AXI byte-address range")

    by_name = {record["name"]: record for record in records}
    qlayer_records = []
    for layer in qlayers:
        name = layer["name"]
        qlayer_records.append({
            **{key: layer[key] for key in ("name", "out", "d_in", "h_block", "n_tiles", "k_tiles")},
            "weight_offset": by_name[f"qweight:{name}"]["offset"],
            "scale_offset": by_name[f"qscale:{name}"]["offset"],
            "bias_offset": by_name[f"qbias:{name}"]["offset"],
            "weight_bytes": by_name[f"qweight:{name}"]["bytes"],
            "scale_bytes": by_name[f"qscale:{name}"]["bytes"],
            "bias_bytes": by_name[f"qbias:{name}"]["bytes"],
            "weight_beats": by_name[f"qweight:{name}"]["bytes"] // AXI_BYTES,
            "scale_beats": by_name[f"qscale:{name}"]["bytes"] // AXI_BYTES,
            "bias_beats": by_name[f"qbias:{name}"]["bytes"] // AXI_BYTES,
        })
    pass_records = [{
        "name": tensor["name"],
        "offset": by_name[f"passthrough:{tensor['name']}"]["offset"],
        "bytes": by_name[f"passthrough:{tensor['name']}"]["bytes"],
        "shape": tensor["shape"],
    } for tensor in passthrough]
    passthrough_ids = {item["name"]: index for index, item in enumerate(pass_records)}
    block_adaln_descriptors = []
    for block in range(14):
        weight_name = f"blocks.{block}.adaln.1.weight"
        bias_name = f"blocks.{block}.adaln.1.bias"
        block_adaln_descriptors.append({
            "block_id": block,
            "weight_id": passthrough_ids[weight_name],
            "weight_offset": pass_records[passthrough_ids[weight_name]]["offset"],
            "weight_bytes": pass_records[passthrough_ids[weight_name]]["bytes"],
            "bias_id": passthrough_ids[bias_name],
            "bias_offset": pass_records[passthrough_ids[bias_name]]["offset"],
            "bias_bytes": pass_records[passthrough_ids[bias_name]]["bytes"],
        })
    descriptor_fields = ("weight_offset", "scale_offset", "bias_offset",
                         "weight_bytes", "scale_bytes", "bias_bytes", "weight_beats",
                         "scale_beats", "bias_beats", "n_tile_stride_bytes",
                         "k_tile_stride_bytes",
                         "out", "d_in", "n_tiles", "k_tiles")
    block_stage_descriptors = [[{
        "layer_id": int(layer_id),
        **{field: int(qlayer_records[int(layer_id)][field])
           for field in ("weight_offset", "scale_offset", "bias_offset",
                         "weight_bytes", "scale_bytes", "bias_bytes", "weight_beats",
                         "scale_beats", "bias_beats", "out", "d_in", "n_tiles",
                         "k_tiles")},
        "n_tile_stride_bytes": int(qlayer_records[int(layer_id)]["k_tiles"]) * WEIGHT_TILE_BYTES,
        "k_tile_stride_bytes": WEIGHT_TILE_BYTES,
    } for layer_id in row] for row in stage_ids]
    runtime_records = [{
        "name": name,
        "offset": by_name[name]["offset"],
        "bytes": by_name[name]["bytes"],
        **metadata,
    } for name, _, metadata in runtime_values]

    digest = _sha256_file(payload_path)
    manifest = {
        "model": "Supra2-IMG",
        "format": "little-endian runtime tensors; N/K-tiled INT8 QLinear weights; FP32 scales/biases",
        "ddr_base": ddr_base,
        "payload": str(payload_path.resolve()),
        "payload_bytes": final_size,
        "axi_512bit_beats": final_size // AXI_BYTES,
        "payload_sha256": digest,
        "components": records,
        "quantized_layers": qlayer_records,
        "passthrough_tensors": pass_records,
        "passthrough_ids": passthrough_ids,
        "block_adaln_descriptors": block_adaln_descriptors,
        "runtime_inputs": runtime_records,
        "block_stage_layer_ids": stage_ids,
        "block_stage_descriptors": block_stage_descriptors,
        "x_embed_layer_id": next(i for i, q in enumerate(qlayers) if q["name"] == "x_embed"),
        "ctx_proj_layer_id": next(i for i, q in enumerate(qlayers) if q["name"] == "ctx_proj"),
        "skip_trace_shape": [50, 14],
        "block_skip_encoding": "bit 1 means skip; bit index is block id",
        "block_skip_masks": skip_masks,
        "block_skip_count": sum(bin(mask).count("1") for mask in skip_masks),
        "skip_trace_skip_ratio": float(np.mean(np.asarray(
            json.loads((export_dir / "skip_trace.json").read_text()), dtype=np.float32))),
        "source_weight_manifest": str((weight_dir / "weight_image_manifest.json").resolve()),
        "source_export_manifest": str((export_dir / "manifest.json").resolve()),
    }
    manifest_path = output_dir / "supra2_dit_ddr_manifest.json"
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    _write_layout_sv(output_dir / "supra2_dit_ddr_layout.sv", manifest)
    verify(output_dir)
    return manifest


def verify(output_dir: Path) -> dict:
    manifest_path = output_dir / "supra2_dit_ddr_manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    payload = Path(manifest["payload"])
    if not payload.is_file() or payload.stat().st_size != manifest["payload_bytes"]:
        raise ValueError("payload size or file is invalid")
    if _sha256_file(payload) != manifest["payload_sha256"]:
        raise ValueError("payload SHA-256 mismatch")
    spans = []
    with payload.open("rb") as stream:
        for item in manifest["components"]:
            offset, size, alignment = int(item["offset"]), int(item["bytes"]), int(item["alignment"])
            if offset % alignment or size <= 0 or offset + size > manifest["payload_bytes"]:
                raise ValueError(f"invalid layout span for {item['name']}")
            stream.seek(offset)
            data = stream.read(size)
            if len(data) != size or _sha256_bytes(data) != item["sha256"]:
                raise ValueError(f"component checksum mismatch for {item['name']}")
            spans.append((offset, offset + size, item["name"]))
    spans.sort()
    for previous, current in zip(spans, spans[1:]):
        if previous[1] > current[0]:
            raise ValueError(f"overlapping payload components: {previous[2]} and {current[2]}")
    if len(manifest["quantized_layers"]) != 100 or len(manifest["passthrough_tensors"]) != 37:
        raise ValueError("full model tensor count mismatch")
    runtime_by_name = {item["name"]: item for item in manifest.get("runtime_inputs", [])}
    expected_runtime_tables = {
        "block_adaln_params_fp16": ([50, 14, 8, 576], 50 * 14 * 8 * 576 * 2),
        "final_adaln_params_fp16": ([50, 2, 576], 50 * 2 * 576 * 2),
        "timestep_embedding_fp16": ([50, 576], 50 * 576 * 2),
    }
    for name, (shape, byte_count) in expected_runtime_tables.items():
        item = runtime_by_name.get(name)
        if item is None or item.get("shape") != shape or item.get("bytes") != byte_count:
            raise ValueError(f"invalid compiled runtime timestep table {name}")
    if len(manifest["block_stage_layer_ids"]) != 14 or any(
            len(row) != 7 for row in manifest["block_stage_layer_ids"]):
        raise ValueError("block-stage index table must be 14x7")
    if len(manifest.get("block_adaln_descriptors", [])) != 14:
        raise ValueError("block AdaLN descriptor table must contain 14 entries")
    for block, descriptor in enumerate(manifest["block_adaln_descriptors"]):
        if descriptor.get("block_id") != block:
            raise ValueError(f"block {block} AdaLN descriptor id mismatch")
        for kind in ("weight", "bias"):
            tensor_name = f"blocks.{block}.adaln.1.{kind}"
            tensor_id = manifest["passthrough_ids"].get(tensor_name)
            tensor = manifest["passthrough_tensors"][tensor_id]
            if (descriptor.get(f"{kind}_id") != tensor_id or
                    descriptor.get(f"{kind}_offset") != tensor["offset"] or
                    descriptor.get(f"{kind}_bytes") != tensor["bytes"]):
                raise ValueError(f"block {block} AdaLN {kind} descriptor mismatch")
    descriptors = manifest.get("block_stage_descriptors", [])
    if len(descriptors) != 14 or any(len(row) != 7 for row in descriptors):
        raise ValueError("block-stage descriptor table must be 14x7")
    for block, row in enumerate(descriptors):
        for stage, descriptor in enumerate(row):
            layer_id = manifest["block_stage_layer_ids"][block][stage]
            if descriptor.get("layer_id") != layer_id:
                raise ValueError(f"block {block} stage {stage} descriptor layer mismatch")
            layer = manifest["quantized_layers"][layer_id]
            for field in ("weight_offset", "scale_offset", "bias_offset", "weight_bytes",
                          "scale_bytes", "bias_bytes", "out", "d_in", "n_tiles", "k_tiles"):
                if descriptor.get(field) != layer[field]:
                    raise ValueError(f"block {block} stage {stage} descriptor {field} mismatch")
            for tensor_kind in ("weight", "scale", "bias"):
                if descriptor.get(f"{tensor_kind}_beats") != \
                        descriptor[f"{tensor_kind}_bytes"] // AXI_BYTES:
                    raise ValueError(f"block {block} stage {stage} {tensor_kind} beat count mismatch")
            if (descriptor.get("k_tile_stride_bytes") != WEIGHT_TILE_BYTES or
                    descriptor.get("n_tile_stride_bytes") !=
                    layer["k_tiles"] * WEIGHT_TILE_BYTES):
                raise ValueError(f"block {block} stage {stage} tile stride mismatch")
    masks = manifest.get("block_skip_masks", [])
    if len(masks) != 50 or any(mask < 0 or mask >= (1 << 14) for mask in masks):
        raise ValueError("block skip table must contain 50 14-bit masks")
    if sum(bin(mask).count("1") for mask in masks) != manifest.get("block_skip_count"):
        raise ValueError("block skip count does not match the skip mask table")
    return {"status": "pass", "payload_bytes": manifest["payload_bytes"],
            "quantized_layers": len(manifest["quantized_layers"]),
            "passthrough_tensors": len(manifest["passthrough_tensors"]),
            "components": len(manifest["components"]),
            "axi_512bit_beats": manifest["axi_512bit_beats"]}


