#!/usr/bin/env python3
"""Build an actual block-13 DDR traffic payload from package/compiler artifacts."""

from __future__ import annotations

import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
DEFAULT_IMAGE = ROOT / "build" / "supra2_quant_export"
DEFAULT_FIXTURE = ROOT / "build" / "supra2_block13_top"
DEFAULT_OUTPUT = ROOT / "build" / "supra2_block13_ddr_traffic"


def hex_words(path: Path, width: int) -> bytes:
    raw = bytes.fromhex("".join(path.read_text(encoding="ascii").split()))
    if len(raw) % width:
        raise ValueError(f"{path} has a partial {width}-byte word")
    return b"".join(raw[i:i + width][::-1] for i in range(0, len(raw), width))


def build(image_dir: Path, fixture_dir: Path, output_dir: Path) -> dict:
    manifest = json.loads((image_dir / "weight_image_manifest.json").read_text())
    qfile = image_dir / "weights_int8_tiled.bin"
    sfile = image_dir / "weight_scales_fp32.bin"
    bfile = image_dir / "weight_biases_fp32.bin"
    layers = {item["name"]: item for item in manifest["quantized_layers"]}
    ordered = [
        "blocks.13.self_attn.qkv", "blocks.13.self_attn.proj",
        "blocks.13.cross_attn.q", "blocks.13.cross_attn.kv",
        "blocks.13.cross_attn.proj", "blocks.13.mlp.0", "blocks.13.mlp.2",
    ]
    components: list[tuple[str, bytes]] = [
        ("activation_x_fp16", hex_words(fixture_dir / "x_input.hex", 2)),
        ("context_fp16", hex_words(fixture_dir / "ctx_packed.hex", 2)),
    ]
    for name in ("ln0_scale", "ln0_shift", "ln1_scale", "ln1_shift",
                 "ln2_scale", "ln2_shift", "gate0", "gate1"):
        components.append((f"adaln_{name}_fp16", hex_words(fixture_dir / f"{name}.hex", 2)))

    with qfile.open("rb") as weights, sfile.open("rb") as scales, bfile.open("rb") as biases:
        for name in ordered:
            item = layers[name]
            weights.seek(item["weight_offset"])
            payload = weights.read(item["weight_bytes"])
            if len(payload) != item["weight_bytes"]:
                raise ValueError(f"truncated packed weights for {name}")
            components.append((f"{name}.int8_tiled", payload))
            scales.seek(item["scale_offset"])
            components.append((f"{name}.scale_fp32", scales.read(item["padded_vector_bytes"])))
            biases.seek(item["bias_offset"])
            components.append((f"{name}.bias_fp32", biases.read(item["padded_vector_bytes"])))

    output_dir.mkdir(parents=True, exist_ok=True)
    payload_path = output_dir / "block13_payload.bin"
    records = []
    with payload_path.open("wb") as stream:
        offset = 0
        for name, content in components:
            padding = (-offset) % 64
            if padding:
                stream.write(bytes(padding))
                offset += padding
            stream.write(content)
            records.append({"name": name, "offset": offset, "bytes": len(content)})
            offset += len(content)
    if offset % 64:
        with payload_path.open("ab") as stream:
            stream.write(bytes((-offset) % 64))
        offset += (-offset) % 64
    result = {
        "block": 13,
        "format": "compiler tiled INT8 weights + little-endian FP16 activations/parameters + FP32 scale/bias",
        "payload": str(payload_path.resolve()),
        "payload_bytes": offset,
        "axi_512bit_beats": offset // 64,
        "components": records,
        "source_weight_image": str((image_dir / "weight_image_manifest.json").resolve()),
        "source_fixture_dir": str(fixture_dir.resolve()),
    }
    (output_dir / "traffic_manifest.json").write_text(json.dumps(result, indent=2) + "\n")
    layout_lines = [
        "// Generated by prepare_block_ddr_traffic.py; do not edit.",
        "package block13_ddr_layout;",
        f"    localparam integer PAYLOAD_BYTES = {offset};",
        f"    localparam integer COMPONENT_COUNT = {len(records)};",
        "    localparam integer COMPONENT_OFFSET [0:COMPONENT_COUNT-1] = '{",
        "        " + ", ".join(str(item["offset"]) for item in records),
        "    };",
        "    localparam integer COMPONENT_BYTES [0:COMPONENT_COUNT-1] = '{",
        "        " + ", ".join(str(item["bytes"]) for item in records),
        "    };",
        "    localparam integer WEIGHT_COMPONENT [0:6] = '{10, 13, 16, 19, 22, 25, 28};",
        "    localparam integer SCALE_COMPONENT [0:6] = '{11, 14, 17, 20, 23, 26, 29};",
        "    localparam integer BIAS_COMPONENT [0:6] = '{12, 15, 18, 21, 24, 27, 30};",
        "endpackage",
        "",
    ]
    (output_dir / "block13_ddr_layout.sv").write_text("\n".join(layout_lines), encoding="ascii")
    return result


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--image-dir", type=Path, default=DEFAULT_IMAGE)
    parser.add_argument("--fixture-dir", type=Path, default=DEFAULT_FIXTURE)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    result = build(args.image_dir, args.fixture_dir, args.output_dir)
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
